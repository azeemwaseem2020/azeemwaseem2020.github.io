const fs = require('node:fs');
const assert = require('node:assert/strict');
const html = fs.readFileSync('mulch-calculator.html', 'utf8');
assert.match(html, /Mulch Calculator: Cubic Yards &amp; Bag Count|Mulch Calculator: Cubic Yards & Bag Count/);
assert.match(html, /Area \(square feet\)/);
assert.match(html, /Mulch depth \(inches\)/);
assert.match(html, /Bag volume \(cubic feet per bag\)/);
assert.match(html, /Math\.ceil\(adjusted\/bag\)/);
assert.match(html, /Number\.isFinite/);
assert.match(html, /waste>100/);
assert.match(html, /out\.textContent=/);
assert.doesNotMatch(html, /out\.innerHTML/);
assert.match(html, /construction-calculators\.html/);
const base = 200 * 3 / 12;
const adjusted = base * 1.10;
assert.equal(base, 50);
assert.ok(Math.abs(adjusted - 55) < 1e-9);
assert.equal(Math.ceil(adjusted / 2), 28);
assert.match(html, /name="author" content="Abdul Qadir"/);
assert.match(html, /Mulch coverage, depth and bag estimates/);
console.log('Mulch calculator volume, bag rounding, validation and output checks passed.');
